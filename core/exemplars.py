"""正例库：资深面试官真实是怎么问的。

来源：用户提供的真实面试实录（字节/大厂 AI PM 面）。
用途：作为 few-shot 塞进出题提示词——模型不会凭空长出"资深"，但它会模仿。

每条是"问 → 答 → 下一刀"的链条，重点在于展示**怎么从一句话往下钻**。
"""

EXEMPLARS = [
    {
        "scene": "AI 客服准确率",
        "chain": [
            ("你刚才说准确率提升到 85%，是从多少提到的？", "从 50% 多提到 87%。"),
            ("你觉得是哪几个比较关键的事情引起了这个变化？",
             "知识库适配、prompt 分层、测试环节。"),
        ],
    },
    {
        "scene": "项目目标是否达成",
        "chain": [
            ("上线之后，你怎么评判它有没有达成你一开始定的目标？",
             "功能指标看 UV/PV，非功能指标看准确率、响应时间。"),
            ("尤其是准确率，这个怎么看？",
             "从知识召回是否完整、是否召回正确两个维度评。"),
            ("机器怎么评测呢？",
             "先做意图识别拆解，再按场景标签召回知识库做匹配。"),
        ],
    },
    {
        "scene": "Bad case 归因",
        "chain": [
            ("在 AI 分身项目里，Bad case 是怎么被发现、归因、并推动迭代的？",
             "分三步：多渠道发现、按节点归类、验证修复效果。"),
            ("按节点归类的时候，你怎么判断是意图识别错了，还是知识问题？",
             "看案例落在哪个环节：分类错、知识缺失/冲突、回复越界、该转人工没转。"),
        ],
    },
    {
        "scene": "个人贡献边界",
        "chain": [
            ("这个项目里，你本人亲手写过或者设计过的部分是什么？",
             "我负责了缓存策略和查询改造。"),
            ("如果把你从项目里拿掉，哪一部分会受到影响？",
             "缓存那部分会没人做，其他人当时在忙别的。"),
        ],
    },
]


def as_prompt() -> str:
    """拼成 few-shot 文本。"""
    lines = ["【资深面试官是这么问的（真实面试实录）】"]
    for i, e in enumerate(EXEMPLARS, 1):
        lines.append(f"\n{i}. {e['scene']}")
        for q, a in e["chain"]:
            lines.append(f"   面试官：{q}")
            lines.append(f"   候选人：{a}")
    lines.append("""
【从上面能看出什么】
- 问题都**很短**，一次只抓一个点；
- 都**接着对方上一句的具体内容**往下钻，不换话题；
- 都在问**判断和依据**（哪几个动作、怎么判断、怎么评测），不问"是什么/做了啥"；
- 不质疑行业默认做法，不含糊地问"详细讲讲".""" )
    return "\n".join(lines)
